"""OCR：把屏幕上一小块字幕条认成英文文本。

用 RapidOCR（PP-OCRv6 的 ONNX 模型，CPU 上跑，不需要显卡）。
模型是打包在 rapidocr 轮子里的，装在 `.venv/Lib/site-packages/rapidocr/models/`，
**首次运行不需要联网下载**——这点很重要，这台机器的代理不稳。

## 那些调参不是猜的，是量出来的

RapidOCR 的默认参数是为"整页文档"设计的，拿来认"又宽又扁的一条字幕"非常吃亏。
本机实测（1600x220 的合成字幕条，5 次中位数，热身后）：

    默认参数                              1082ms   ← 而且这一档根本没认出来
    limit_type=max / 1536                  225ms
      + 关方向分类器                        190ms
      + 关纵向补白                          171ms

三处改动，7 倍提速，准确率还是满分。原因分别是：

1. **`Det.limit_type` 默认是 `min`**，意思是"把**短边**撑到 736"。字幕条短边只有
   一两百像素，于是 1600x220 被**放大成 5353x736**（390 万像素）再送进检测网络。
   改成 `max`（限制长边）后只需算 1280x176，差 20 倍。这是慢的主因。
2. **`use_cls`** 是文字方向分类器（判断有没有转 180 度），会在每个检测框上多跑一次
   模型。字幕永远是水平的，纯属浪费。
3. **`use_vertical_padding` 默认开**，会在宽高比超过 8 时**上下补白**：
   1600x110 会被补成 1600x400——比不补白时还大，所以"框紧一点"反而更慢（实测过）。
   关掉它，框得越紧越省。

顺带验证过但**没有采用**的：把识别模型换成英文专用的（`Rec.lang_type = en`）。
实测 129ms vs 124ms，一样快甚至略慢（识别耗时主要在卷积骨干上，不在最后那层
分类维度），却要多联网下一个模型。中文模型认英文本来就准（实测置信度 0.993），
所以留用自带的那个，整个安装保持离线。

## 排版假设

只取**最下面** `max_lines` 行：字幕在框的下部，多出来的（进度条、标题栏）
在上面。框选时刻意避开了 CC 按钮和 "Auto-generated" 标记，这里再兜一道。
"""

from __future__ import annotations

import logging
import time
from dataclasses import dataclass, field

import numpy as np

from .config import OcrCfg

log = logging.getLogger(__name__)

# 调参真源。probe_ocr.py 也 import 这里，保证探针和正式代码用的是同一套参数。
TUNED_PARAMS: dict[str, object] = {
    "Det.limit_type": "max",              # 限制长边，别把细长的字幕条放大（见文件头）
    "Det.limit_side_len": 1280,
    "Global.use_cls": False,              # 字幕不会倒过来
    "Global.use_vertical_padding": False,  # 别偷偷补白，补了"框紧"就白费
    "Global.log_level": "warning",        # 那几行 INFO（用了哪个模型）会刷屏，需要时改回 info
}

# 这些是播放器的界面文字，不是字幕。框选时应该避开，认出来了也一律丢掉。
# 比对时用小写 + 去空格，`CC` 和 `Auto-generated` 都能命中。
REJECT_LINES = {
    "cc", "cc1", "auto-generated", "auto generated", "autogenerated",
    "subtitles", "settings", "watch later", "share", "subscribe",
}


@dataclass(frozen=True)
class OcrLine:
    """一行识别结果。y 用来排序和判断"哪一行在上面"。"""
    text: str
    score: float
    x: float = 0.0
    y: float = 0.0


@dataclass(frozen=True)
class Reading:
    """一帧的完整读数。

    `t` 是这一帧的抓取时刻（time.monotonic 口径）。**字幕状态机的所有时间判断
    都只认这个值，绝不自己调时钟**——这是自检能确定性地测状态机的前提。
    """
    text: str
    lines: tuple[OcrLine, ...] = ()
    score: float = 0.0
    elapse_s: float = 0.0
    t: float = 0.0

    @property
    def empty(self) -> bool:
        return not self.text.strip()


def _line_geometry(box) -> tuple[float, float]:
    """从检测框里取出左上角坐标 (x, y)。

    RapidOCR 的 boxes 是 (N, 4, 2) 的数组，正常情况下可以直接取；但形状偶尔
    会变（不同版本/不同后端），而且这只是用来排序的辅助信息，取不到就算了——
    不该为了一个 y 坐标把整帧读数搞崩。
    """
    try:
        pts = np.asarray(box, dtype=float).reshape(-1, 2)
        return float(pts[:, 0].min()), float(pts[:, 1].min())
    except Exception:
        return 0.0, 0.0


def _unpack(result) -> tuple[list[str], list[float], list]:
    """拆出 (文本, 置信度, 检测框)，兼容 RapidOCR 两代返回值。

    3.x 返回带 .txts/.scores/.boxes 的对象，2.x 返回 (entries, elapse)。
    """
    if isinstance(result, tuple):
        entries = result[0] or []
        texts = [e[1] for e in entries if len(e) >= 3]
        scores = [float(e[2]) for e in entries if len(e) >= 3]
        boxes = [e[0] for e in entries if len(e) >= 3]
        return texts, scores, boxes
    texts = list(getattr(result, "txts", None) or [])
    raw = getattr(result, "scores", None)
    scores = [float(s) for s in (raw if raw is not None else [])]
    raw_boxes = getattr(result, "boxes", None)
    boxes = list(raw_boxes) if raw_boxes is not None else []
    return texts, scores, boxes


def _quiet_engine_log() -> None:
    """把引擎自己的日志压到 ERROR。

    它每认一次空画面就打一条 `The text detection result is empty` 的 warning
    （rapidocr/main.py 捕获 RapidOCRError 之后 logger.warning(e)）。而**空画面是常态**：
    字幕换气的间隙、暂停、广告、没开字幕的时候都是空的。原样放行的话，日志文件会被
    这一行刷满，真正要看的东西全被埋掉。

    注意**必须在这里设、不能放在 import 之后**：rapidocr 在 import 时就把这个 logger
    的级别设成 INFO 了（utils/log.py 的模块级 `Logger(log_level=logging.INFO, ...)`），
    早设会被它覆盖回去。所以放在引擎构造完成之后。
    """
    logging.getLogger("RapidOCR").setLevel(logging.ERROR)


class OcrEngine:
    """OCR 引擎。构造一次、长期复用（每次构造都要加载 ONNX 模型，很贵）。"""

    def __init__(self, cfg: OcrCfg) -> None:
        self.cfg = cfg
        self.last_error: str | None = None
        self._engine = self._build(cfg)

    def _build(self, cfg: OcrCfg):
        from rapidocr import RapidOCR

        params = dict(TUNED_PARAMS)
        # 置信度门槛交给引擎内部的过滤器（比我们拿到结果再筛更省一点）
        params["Global.text_score"] = cfg.min_confidence
        try:
            engine = RapidOCR(params=params)
        except Exception as e:
            # 参数不被接受时（换版本了）退回默认参数：慢一点，但还能用。
            # 静默吞掉不行——这条必须留痕，否则以后查"为什么变慢了"会毫无线索。
            log.warning("RapidOCR 不接受调优参数（%s: %s），退回默认参数（会明显变慢）",
                        type(e).__name__, e)
            self.last_error = f"调优参数被拒绝：{e}"
            engine = RapidOCR()
        _quiet_engine_log()
        return engine

    def read(self, frame: np.ndarray, t: float) -> Reading:
        """认一帧。**任何异常都吞掉并返回空读数**，同时记录到 last_error。

        绝不让 OCR 的偶发失败把采集线程打死——屏幕上的画面千奇百怪，
        单帧失败是正常现象，而线程死了用户只会看到"字幕再也不出来了"。
        """
        t0 = time.perf_counter()
        try:
            raw = self._engine(frame)
        except Exception as e:
            self.last_error = f"{type(e).__name__}: {e}"
            log.warning("OCR 失败: %s", self.last_error)
            return Reading(text="", t=t, elapse_s=time.perf_counter() - t0)

        elapsed = time.perf_counter() - t0
        texts, scores, boxes = _unpack(raw)

        kept: list[OcrLine] = []
        for i, text in enumerate(texts):
            score = scores[i] if i < len(scores) else 0.0
            clean = (text or "").strip()
            if not clean:
                continue
            if score < self.cfg.min_confidence:
                continue
            if clean.lower().replace(" ", "") in REJECT_LINES:
                continue
            x, y = _line_geometry(boxes[i]) if i < len(boxes) else (0.0, 0.0)
            kept.append(OcrLine(text=clean, score=score, x=x, y=y))

        if not kept:
            return Reading(text="", t=t, elapse_s=elapsed)

        # 按位置从上到下排，然后只保留最下面的几行——字幕在框的下部，
        # 多出来的行（比分板、标题、进度条）在上面。
        kept.sort(key=lambda line: line.y)
        if len(kept) > self.cfg.max_lines:
            dropped = len(kept) - self.cfg.max_lines
            log.debug("读到 %d 行，只取最下面 %d 行（丢掉上面 %d 行）",
                      len(kept), self.cfg.max_lines, dropped)
            kept = kept[-self.cfg.max_lines:]

        return Reading(
            text="\n".join(line.text for line in kept),
            lines=tuple(kept),
            score=sum(line.score for line in kept) / len(kept),
            elapse_s=elapsed,
            t=t,
        )

    def close(self) -> None:
        """放掉 ONNX 会话。程序退出时调，正常使用中不用管。"""
        try:
            self._engine = None
        except Exception:
            pass


def main() -> int:
    """命令行：认一张图，把读到的行打出来。调试用。"""
    import sys
    from pathlib import Path

    if len(sys.argv) < 2:
        print("用法: python -m livetranslate_ocr.ocr 图片.png")
        return 2

    import cv2

    cfg = OcrCfg()
    engine = OcrEngine(cfg)
    path = Path(sys.argv[1])
    # cv2 读进来是 BGR，RapidOCR 期望 RGB
    bgr = cv2.imread(str(path))
    if bgr is None:
        print(f"读不了这张图: {path}")
        return 1
    rgb = bgr[:, :, ::-1].copy()

    t0 = time.monotonic()
    reading = engine.read(rgb, t=t0)
    print(f"耗时 {reading.elapse_s * 1000:.0f} ms，均分 {reading.score:.3f}")
    for line in reading.lines:
        print(f"  [{line.score:.3f}] y={line.y:7.1f}  {line.text!r}")
    if reading.empty:
        print("  (什么都没读到)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
